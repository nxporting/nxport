/// Writes the Miis `flags` selects into `out` (elements of `stride` bytes; CharInfoElement adds the source).
unsafe fn get(out_count: *mut i32, out: *mut u8, capacity: i32, flags: i32, stride: usize) -> u32 {
    let mut n = 0;
    let mut result = RESULT_SUCCESS;
    if flags & SOURCE_FLAG_DEFAULT != 0 {
        for i in 0..DEFAULT_INDICES.len() {
            if n >= capacity.max(0) as usize {
                result = RESULT_OVERFLOW;
                break;
            }
            if !out.is_null() {
                let e = out.add(n * stride);
                std::ptr::write_bytes(e, 0, stride);
                std::ptr::copy_nonoverlapping(default_char_info(i).as_ptr(), e, CHAR_INFO_SIZE);
                if stride > CHAR_INFO_SIZE {
                    (e.add(CHAR_INFO_SIZE) as *mut u32).write_unaligned(SOURCE_DEFAULT);
                }
            }
            n += 1;
        }
    }
    if !out_count.is_null() {
        *out_count = n as i32;
    }
    result
}

