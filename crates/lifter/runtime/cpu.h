// Guest CPU state and the helpers lifted code uses (nxport-lifter; docs/windows-port.md). Compiled with clang (zig cc
// for players): GNU C, __int128, musttail. Based on LAS Recomp's runtime/cpu.h (MIT, see LICENSE-LASRecomp).
//
// Calls and returns: a call sets x30 to the return address and calls the target's C function (or rt_dispatch for a
// target known only at run time); `ret` sets c->pc to its register's value and returns from the C function. After
// each call the caller checks that c->pc is the return address it set; anything else (longjmp-style code, a function
// that returns elsewhere) continues at c->pc through rt_dispatch. Host functions the guest calls (HLE) follow the same
// protocol: they set c->pc = c->x[30] before returning. guest_call-style entries from the host set x30 to
// RT_RETURN_TO_HOST, which rt_dispatch returns on.
#pragma once
#include <stddef.h>
#include <stdint.h>
#include <string.h>

typedef struct __attribute__((aligned(16))) Cpu {
    uint64_t x[32];       // 0: x0-x30 (x[31] unused; sp is separate)
    uint64_t sp;          // 256
    uint64_t pc;          // 264: dispatch target / where a return went
    uint64_t nzcv;        // 272: flags in bits 31..28
    uint64_t tpidr;       // 280
    uint64_t tpidrro;     // 288
    uint64_t excl_addr;   // 296: exclusive monitor (~0: open)
    uint64_t excl_val;    // 304
    void *thread;         // 312: the runtime's thread object
    uint64_t fpcr;        // 320
    uint64_t fpsr;        // 328
    uint64_t excl_val_hi; // 336: high half of an exclusive pair
    uint8_t _pad[512 - 344];
    unsigned __int128 v[32]; // 512
} Cpu;

_Static_assert(offsetof(Cpu, sp) == 256, "sp");
_Static_assert(offsetof(Cpu, pc) == 264, "pc");
_Static_assert(offsetof(Cpu, nzcv) == 272, "nzcv");
_Static_assert(offsetof(Cpu, tpidr) == 280, "tpidr");
_Static_assert(offsetof(Cpu, excl_val_hi) == 336, "excl_val_hi");
_Static_assert(offsetof(Cpu, v) == 512, "v");
_Static_assert(sizeof(Cpu) == 1024, "size");

typedef void (*GuestFn)(Cpu *);

// The guest library exports only its function tables: a game has more functions than a PE export table holds (64K),
// and an explicit export turns off the MinGW linker's export-everything default.
#ifdef _WIN32
#define RT_EXPORT __declspec(dllexport)
#define RT_FN
#else
#define RT_EXPORT __attribute__((visibility("default")))
#define RT_FN __attribute__((visibility("hidden")))
#endif

#define RT_RETURN_TO_HOST 0ull

